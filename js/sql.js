import { buildRelationalModel } from './schema.js';
import { downloadBlob } from './utils.js';

const quoteWith = (open, close = open) => name => open + name.split(close).join(close + close) + close;

export const DIALECTS = {
    mysql: { label: 'MySQL / MariaDB', quote: quoteWith('`'), inlineForeignKeysOnly: false },
    postgres: { label: 'PostgreSQL', quote: quoteWith('"'), inlineForeignKeysOnly: false },
    sqlite: { label: 'SQLite', quote: quoteWith('"'), inlineForeignKeysOnly: true },
};

/** Builds the SQL script for the diagram, downloads it and returns the model. */
export function generateSQL(dialectName = 'mysql') {
    const model = buildRelationalModel();
    const sql = buildSQL(model, dialectName);
    downloadBlob(new Blob([sql], { type: 'text/plain' }), 'database.sql');
    return model;
}

export function buildSQL(model, dialectName = 'mysql') {
    const dialect = DIALECTS[dialectName] || DIALECTS.mysql;
    const q = name => dialect.quote(String(name).trim().replace(/\s+/g, '_'));

    const out = [
        `-- Generated by ER Diagram Maker (${dialect.label})`,
        '-- All columns use VARCHAR(255) – adjust the data types as needed.',
    ];
    const notes = [...model.warnings, ...model.sqlNotes];
    if (notes.length) {
        out.push('--', '-- Warnings:');
        notes.forEach(n => out.push(`--   ${n.replace(/\s+/g, ' ')}`));
    }
    if (dialectName === 'sqlite') out.push('', 'PRAGMA foreign_keys = ON;');
    out.push('');

    // Referenced tables first; foreign keys inside a cycle are added afterwards
    const created = new Set();
    const deferred = [];
    for (const table of topologicalOrder(model.tables)) {
        if (!table.columns.length) {
            out.push(`-- Table ${q(table.name)} has no columns and was skipped.`, '');
            continue;
        }
        const lines = table.columns.map(c => `    ${q(c.name)} VARCHAR(255)${c.isPK || c.notNull ? ' NOT NULL' : ''}`);
        const pk = table.columns.filter(c => c.isPK);
        if (pk.length) lines.push(`    PRIMARY KEY (${pk.map(c => q(c.name)).join(', ')})`);
        table.uniques.forEach(cols => lines.push(`    UNIQUE (${cols.map(q).join(', ')})`));

        for (const fk of table.foreignKeys) {
            const clause = `FOREIGN KEY (${fk.columns.map(q).join(', ')}) REFERENCES ${q(fk.refTable.name)} (${fk.refColumns.map(q).join(', ')})`;
            if (dialect.inlineForeignKeysOnly || fk.refTable === table || created.has(fk.refTable)) {
                lines.push(`    ${clause}`);
            } else {
                deferred.push(`ALTER TABLE ${q(table.name)} ADD ${clause};`);
            }
        }

        out.push(`CREATE TABLE ${q(table.name)} (\n${lines.join(',\n')}\n);`, '');
        created.add(table);
    }

    if (deferred.length) out.push('-- Foreign keys between tables that reference each other', ...deferred, '');
    return out.join('\n');
}

function topologicalOrder(tables) {
    const order = [];
    const seen = new Set();
    const visit = table => {
        if (seen.has(table)) return;
        seen.add(table);
        table.foreignKeys.forEach(fk => { if (fk.refTable !== table) visit(fk.refTable); });
        order.push(table);
    };
    tables.forEach(visit);
    return order;
}
